# PART 6: Tool-forced output + schema design + semantic validation
# ============================================================================
# FORCED TOOL = STRUCTURED OUTPUT  (lesson 07: tool calling)
#   request: tools=[record_invoice(schema)]  tool_choice=record_invoice
#        │
#        ▼   model MUST "call" it ─▶ no prose, no other tool
#   response: tool_use {name: record_invoice, input: {...}}
#        │                                     ▲ this dict IS your data
#        ▼   you never run a tool ─▶ just read `input`
#   schema check ✓ ─▶ semantic check (dates, ranges, sums) ✓/✗ ─▶ use

INVOICE_TOOL = {
    "name": "record_invoice",
    "description": "Record the fields of ONE invoice found in the document.",
    "input_schema": {
        "type": "object",
        "properties": {
            "invoice_id": {"type": "string", "description": "As printed, e.g. INV-0042"},
            "issue_date": {"type": "string", "description": "YYYY-MM-DD"},
            "due_date": {"type": "string", "description": "YYYY-MM-DD, >= issue_date"},
            "currency": {"type": "string", "enum": ["EUR", "USD", "GBP"]},
            "total": {"type": "number", "description": "Grand total incl. tax"},
        },
        "required": ["invoice_id", "issue_date", "due_date", "currency", "total"],
        "additionalProperties": False,
    },
}

SCHEMA_VALID_SAMPLES = [  # all of these pass the schema above
    {"invoice_id": "INV-0042", "issue_date": "2026-03-01", "due_date": "2026-03-31",
     "currency": "EUR", "total": 1250.0},
    {"invoice_id": "INV-0043", "issue_date": "2026-03-10", "due_date": "2026-02-10",
     "currency": "USD", "total": 99.5},
    {"invoice_id": "INV-0044", "issue_date": "2026-02-30", "due_date": "2026-03-30",
     "currency": "GBP", "total": 40.0},
    {"invoice_id": "INV-0045", "issue_date": "2026-04-01", "due_date": "2026-05-01",
     "currency": "EUR", "total": -300.0},
    {"invoice_id": "INV-0046", "issue_date": "1996-04-01", "due_date": "1996-05-01",
     "currency": "EUR", "total": 80.0},
]


def semantic_errors(inv: dict, today=datetime.date(2026, 10, 27)) -> list[str]:
    errors = []
    try:
        issue = datetime.date.fromisoformat(inv["issue_date"])
        due = datetime.date.fromisoformat(inv["due_date"])
    except ValueError as e:
        return [f"impossible date ({e})"]
    if due < issue:
        errors.append("due_date before issue_date")
    if not today - datetime.timedelta(days=5 * 365) <= issue <= today:
        errors.append("issue_date outside last 5 years")
    if inv["total"] <= 0:
        errors.append("total must be > 0")
    return errors


def part6_tool_forced():
    print("######## PART 6 -- Tool-forced output and schema design ########\n")
    request = {"tools": [{"name": INVOICE_TOOL["name"], "input_schema": "..."}],
               "tool_choice": {"type": "tool", "name": "record_invoice"}}
    print(f"  Anthropic-style tools      : {json.dumps(request['tools'])}")
    print(f"  Anthropic-style tool_choice: {json.dumps(request['tool_choice'])}")
    print('  OpenAI-style tool_choice   : {"type": "function", "function": '
          '{"name": "record_invoice"}}')
    props = INVOICE_TOOL["input_schema"]["properties"]
    print(f"  Schema: {len(props)} flat fields, all required, "
          f"{sum('description' in p for p in props.values())} with descriptions, "
          f"1 enum, no extra keys\n")
    response = {"type": "tool_use", "name": "record_invoice",
                "input": SCHEMA_VALID_SAMPLES[0]}
    print(f"  Simulated response block: {json.dumps(response)[:70]}...")
    print("  -> response.input IS the structured data. Nothing gets executed.\n")
    print("  Schema-valid is not the same as correct -- semantic checks in code:")
    for inv in SCHEMA_VALID_SAMPLES:
        errs = semantic_errors(inv)
        verdict = "OK" if not errs else "REJECT: " + "; ".join(errs)
        print(f"    {inv['invoice_id']}  issue {inv['issue_date']}  due {inv['due_date']}"
              f"  total {inv['total']:>7}  -> {verdict}")
    print("""
  Schema design tips:
    - enums over free text   ("EUR" not "euros", "Euro", "EUR ")
    - small and flat         nested / huge schemas confuse models and some
                             constrained decoders reject them
    - mark fields required   optional fields get silently skipped
    - describe every field   descriptions are the only docs the model reads
    - allow "unknown"        an enum value or null beats an invented answer
    - validate semantics     dates, ranges, sums, cross-field rules in CODE,
                             then retry with the error (lesson 03 PART 5)
""")


# ============================================================================
# PART 7: Images become tokens
# ============================================================================
# IMAGE ─▶ PATCHES ─▶ VECTORS ─▶ TOKENS IN THE SAME STREAM
#   ┌────┬────┐
#   │ p1 │ p2 │   each patch: pixels ─▶ flatten ─▶ × W ─▶ one vector
#   ├────┼────┤                                        (one "token")
#   │ p3 │ p4 │
#   └────┴────┘
#   stream: [What][is][in][this][?] [p1][p2][p3][p4] [answer...]
#           text tokens             image tokens     same attention

PATCH = 4


def toy_image(size=8) -> list[list[int]]:
    """8x8 grayscale: a bright square in the top-left on a dark gradient."""
    return [[(200 if r < 4 and c < 4 else 10 * (r + c)) for c in range(size)]
            for r in range(size)]


def patches(img):
    n = len(img) // PATCH
    for pr in range(n):
        for pc in range(n):
            yield [img[r][c] for r in range(pr * PATCH, (pr + 1) * PATCH)
                   for c in range(pc * PATCH, (pc + 1) * PATCH)]


def fit(w, h, longest):
    s = min(1.0, longest / max(w, h))
    return round(w * s), round(h * s)


def tokens_tiles(w, h):
    """Toy formula A: fit in 2048px, then 85 + 170 tokens per 512px tile."""
    w, h = fit(w, h, 2048)
    return 85 + 170 * math.ceil(w / 512) * math.ceil(h / 512)


def tokens_area(w, h):
    """Toy formula B: fit in 1568px, then about one token per 750 pixels."""
    w, h = fit(w, h, 1568)
    return math.ceil(w * h / 750)


IMAGES = [("icon 256x256", 256, 256), ("photo 1024x768", 1024, 768),
          ("screenshot 1920x1080", 1920, 1080), ("phone photo 4032x3024", 4032, 3024),
          ("A4 page scan 1700x2200", 1700, 2200)]


def part7_image_tokens():
    print("######## PART 7 -- Images become tokens ########\n")
    rng = random.Random(7)
    W = [[rng.uniform(-1, 1) / 16 for _ in range(3)] for _ in range(PATCH * PATCH)]
    print(f"  Toy 8x8 image -> {PATCH}x{PATCH} patches -> 16 pixels each -> x W(16x3):")
    for i, p in enumerate(patches(toy_image()), 1):
        vec = [sum(px / 255 * W[j][k] for j, px in enumerate(p)) for k in range(3)]
        print(f"    patch {i}: mean pixel {sum(p) / len(p):5.1f} -> vector "
              f"[{', '.join(f'{v:+.3f}' for v in vec)}]")
    print("  stream: [What][is][this][?] [img1][img2][img3][img4]  (one sequence)\n")

    print("  Token cost (TOY formulas -- real ones differ by provider/model):")
    print("    A = fit 2048px, 85 + 170 per 512px tile    B = fit 1568px, w*h/750")
    print(f"    {'image':<24} {'A tokens':>8} {'B tokens':>8}   B as text")
    for name, w, h in IMAGES:
        b = tokens_area(w, h)
        print(f"    {name:<24} {tokens_tiles(w, h):>8,} {b:>8,}   ~{b * 3 // 4:,} words")
    page_text = est_tokens("word " * 500)
    page_img = tokens_area(1700, 2200)
    print(f"\n  One page of text, 500 words, as TEXT : {page_text:>5} tokens")
    print(f"  The same page as an IMAGE (formula B): {page_img:>5} tokens "
          f"({page_img / page_text:.1f}x)")
    pages = 20
    print(f"  A {pages}-page PDF sent as text + page images: {pages} x "
          f"({page_text} + {page_img}) = {pages * (page_text + page_img):,} tokens")
    secs, per_sec = 60, 25
    print(f"  Audio (toy: {per_sec} tokens/s): a {secs}s clip = {secs * per_sec:,} tokens;"
          f" a transcript of it ~ {est_tokens('word ' * 150)} tokens")
    print("""
  PDFs are usually sent as BOTH extracted text and an image of each page,
  so charts and layout survive -- and you pay for both. Audio is cut into
  short frames that become tokens the same way; transcribing first is far
  cheaper when you only need the words.
""")


