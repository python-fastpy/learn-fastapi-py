"""Lesson 13 -- Reasoning models, structured output in depth, multimodal inputs
==============================================================================

WHY THIS MATTERS:
  Three features show up in almost every modern LLM API, and each one is
  easy to misuse because the mechanism is hidden:

      prompt ──▶ [ hidden THINKING tokens ] ──▶ [ visible answer ]   A
                        billed as output          ▲
                                                  │ constrained to   B
                                                  │ YOUR schema
      image / PDF / audio ──▶ patches ──▶ tokens in the SAME stream  C

  A. Reasoning models think before answering -- great for hard problems,
     pure waste (cost + latency) on easy ones.
  B. "Return JSON" in a prompt is a request; schema-constrained decoding
     is a guarantee. Lesson 03 PART 5 showed validate + retry; here we
     measure WHY the stronger levels exist and how they work inside.
  C. Images are not free "attachments" -- they become tokens, and their
     size decides both the bill and how well small text can be read.

WHAT YOU'LL LEARN:
  1. What a reasoning model is: a thinking block, then the answer
  2. Thinking budget / effort: accuracy vs cost vs latency, easy vs hard
  3. When to use a reasoning model vs "think step by step", and its rules
  4. Three levels of structured output, with failure rates measured
  5. Constrained decoding mechanically: masking invalid tokens per step
  6. Tool-forced output + schema design tips + semantic validation
  7. Images become tokens: patches, token cost formulas, PDFs, audio
  8. Practical multimodal rules: resize, crop, OCR, small-text risk

Concepts:
  - Thinking tokens: hidden reasoning the model writes before the answer
  - Thinking budget / effort: a cap or dial for how much it may think
  - JSON mode: output is guaranteed to PARSE, any shape
  - Constrained decoding: tokens that break the schema get probability 0
  - Forced tool choice: make the model "call" a tool just to get its args
  - Patch: a small square of an image, turned into one vector / token

PREREQUISITES: Lessons 01-05. Pure Python, no packages, no credentials.

Level: ADVANCED

Run:  uv run python advanced/13_reasoning_and_structured_output.py
      (from learn-llm-fundamentals)
"""

import datetime
import json
import math
import random

PRICE_OUT = 15.00      # $ per 1M output tokens -- example rate (lesson 03)
TOKENS_PER_SEC = 90    # simulated output speed
TTFT = 0.6             # simulated time to first token, seconds


def est_tokens(text: str) -> int:
    """~4 chars per token, same rough rule as lesson 03."""
    return max(1, math.ceil(len(text) / 4))


def bar(frac: float, width: int = 20) -> str:
    n = round(max(0.0, min(1.0, frac)) * width)
    return "#" * n + "." * (width - n)


# ============================================================================
# PART 1: What a reasoning model is
# ============================================================================
# ONE OUTPUT STREAM, TWO BLOCKS
#   ┌──────────────────────────────────────────┬────────────────────┐
#   │ THINKING  ░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░ │ ANSWER  ██████████ │
#   │ scratch work, hidden or summarized       │ what the user sees │
#   └──────────────────────────────────────────┴────────────────────┘
#     ▲ generated by the SAME next-token loop (lesson 01), just first
#     usage.output_tokens = thinking + answer  ─▶ you pay for both

THINKING = ("Departs 09:40. Trip is 2h35m. 09:40 + 2h = 11:40. 11:40 + 35m = "
            "12:15. Check: 20 min to 10:00, then 2h15m more -> 12:15. Time "
            "zone? Both times are local on the same line, so no change. "
            "Answer 12:15.")
ANSWER = "The train arrives at 12:15."


def part1_what_is_reasoning():
    print("######## PART 1 -- What a reasoning model is ########\n")
    print("  Question: 'A train leaves 09:40, the trip takes 2h35m. Arrival?'\n")
    t_think, t_ans = est_tokens(THINKING), est_tokens(ANSWER)
    print(f"  thinking block ({t_think} tokens, hidden):")
    print(f"      {THINKING[:66]}...")
    print(f"  answer block   ({t_ans} tokens, shown):")
    print(f"      {ANSWER}\n")
    scale = 60 / (t_think + t_ans)
    stream = "T" * round(t_think * scale) + "|" + "A" * max(1, round(t_ans * scale))
    print(f"  token stream:  {stream}")
    print("                 T = thinking token   | = end of thinking   A = answer\n")
    print(f"  usage: output_tokens = {t_think} + {t_ans} = {t_think + t_ans}"
          f"   ({t_think / (t_think + t_ans):.0%} of the bill is thinking)")
    print("""
  Nothing new happens inside the model: it was TRAINED to write a long
  scratchpad first, then the answer. The API separates the two blocks;
  depending on the provider you get the thinking in full, as a summary,
  or not at all -- but you are always billed for all of it.
""")


# ============================================================================
# PART 2: Thinking budget / effort -- accuracy vs cost vs latency
# ============================================================================
# DIMINISHING RETURNS  (shape of the simulated curves below)
#   accuracy
#    100% ┤ easy ●──●──●──●──●   flat: already right without thinking
#         │
#         │                  ●──●  hard: big jump, then flattens
#         │            ●
#         │      ●
#    ~20% ┤ hard ●
#         └──┬──────┬──────┬──────┬──────┬──▶ thinking budget (tokens)
#            0     1k     4k    16k    32k
#   cost and latency grow ~linearly with tokens actually USED

BUDGETS = [0, 1024, 4096, 16384, 32768]


def make_problems(n, seed, median_need, base, ceiling):
    """Each simulated problem needs some thinking tokens to be solved.

    need    : tokens of reasoning required (log-normal around median_need)
    capable : the model CAN solve it at all (prob = ceiling)
    lucky   : a capable model gets it right with NO thinking (prob = base)
    """
    rng = random.Random(seed)
    return [(rng.lognormvariate(math.log(median_need), 0.9),
             rng.random() < ceiling, rng.random() < base) for _ in range(n)]


def run_budget(problems, budget):
    correct = used = 0
    for need, capable, lucky in problems:
        correct += capable and (need <= budget or lucky)
        used += min(budget, need)                 # model stops when it is done
    return correct / len(problems), used / len(problems)


def part2_budget():
    print("######## PART 2 -- Thinking budget: accuracy vs cost (SIMULATED) ########\n")
    sets = {"easy": make_problems(200, 1, median_need=250, base=0.99, ceiling=0.97),
            "hard": make_problems(200, 2, median_need=2500, base=0.25, ceiling=0.88)}
    answer_tokens = 200
    for name, problems in sets.items():
        print(f"  {name} set, 200 simulated problems")
        print(f"  {'budget':>7}  {'accuracy':<30} {'avg think':>9} "
              f"{'$/1k calls':>10} {'latency':>8}")
        rows = []
        for b in BUDGETS:
            acc, used = run_budget(problems, b)
            cost = (used + answer_tokens) * PRICE_OUT / 1e6 * 1000
            secs = TTFT + (used + answer_tokens) / TOKENS_PER_SEC
            gain = "" if not rows else f" ({(acc - rows[-1][0]) * 100:+.1f} pt)"
            print(f"  {b:>7}  {bar(acc)} {acc:6.1%}{gain:<11} {used:>7.0f}  "
                  f"${cost:>8.2f} {secs:>7.1f}s")
            rows.append((acc, cost))
        (a0, c0), (a1, c1), (a2, c2) = rows[0], rows[-2], rows[-1]
        print(f"  -> no thinking vs max: {(a2 - a0) * 100:+.1f} pt for {c2 / c0:.1f}x cost;"
              f" last doubling (16k->32k): {(a2 - a1) * 100:+.1f} pt\n")
    print("""  Reading it:
    - easy: thinking adds ~nothing to accuracy; the model already knew.
      The budget is a CAP, so it only spends a few hundred tokens -- but
      that is still pure extra cost and latency for zero gain.
    - hard: accuracy climbs steeply, then flattens; the last doubling of
      the budget buys little. Pick the knee, not the maximum.
    - Providers expose this as an effort level (low/medium/high) or a
      token budget. Measure on YOUR eval set (lesson 11) to pick one.
""")


# ============================================================================
# PART 3: When to use a reasoning model -- and how to prompt one
# ============================================================================
# DECISION FLOW
#   Many steps, math, code, planning, tricky constraints?
#     ├─ no ─▶ normal model (low effort). Classification, extraction, chat.
#     └─ yes ─▶ latency-critical or very high volume?
#               ├─ yes ─▶ normal model + "think step by step" (lesson 05)
#               │         or a low effort setting
#               └─ no ──▶ reasoning model; tune effort on an eval set

DECISION_TABLE = [
    ("Classify / extract / route", "normal", "one-step task; thinking is waste"),
    ("Chat, rewrite, summarize", "normal", "fluency, not reasoning"),
    ("Multi-step math / logic", "reasoning", "needs scratch work; big gains"),
    ("Hard code change, debugging", "reasoning", "planning + checking pays off"),
    ("Agent planning, many tools", "reasoning*", "*medium effort; watch latency"),
    ("Real-time voice, autocomplete", "normal", "latency budget < 1 s"),
    ("High volume, cheap & good enough", "normal + CoT", "CoT only where it helps"),
]


def build_request(model_kind: str, **params) -> tuple[dict | None, str | None]:
    """Simulated API-side check: thinking models often reject sampling knobs."""
    rejected = {"temperature", "top_p", "top_k"} & params.keys()
    if model_kind == "reasoning" and rejected:
        return None, f"400: {sorted(rejected)} not supported with thinking"
    return {"model": model_kind, **params}, None


def part3_when_to_use():
    print("######## PART 3 -- When to use a reasoning model ########\n")
    print(f"  {'task':<34} {'use':<13} why")
    print(f"  {'-' * 34} {'-' * 13} {'-' * 32}")
    for task, use, why in DECISION_TABLE:
        print(f"  {task:<34} {use:<13} {why}")

    print("\n  Sampling params (lesson 02) on a thinking model -- simulated API:")
    for kind, params in [("normal", {"temperature": 0.2}),
                         ("reasoning", {"temperature": 0.2}),
                         ("reasoning", {"effort": "medium"})]:
        req, err = build_request(kind, **params)
        print(f"    {kind:<10} {str(params):<22} -> {err or 'ok: ' + json.dumps(req)}")

    over = ("Step 1: read the code. Step 2: list functions. Step 3: for each "
            "function check nulls. Step 4: ... Step 12: write the answer.")
    goal = ("Goal: find the bug causing the null-pointer crash in checkout. "
            "Constraints: don't change the public API; explain the fix in "
            "3 sentences. Done = a patch plus the explanation.")
    print(f"\n  Over-specified prompt ({est_tokens(over)} tokens): dictates the steps")
    print(f"  Goal + constraints  ({est_tokens(goal)} tokens): says what DONE looks like")
    print("""
  Rules for reasoning models:
    1. Give the goal, constraints and success criteria -- not the steps.
       Your 12 steps are usually worse than the model's own plan.
    2. Don't add "think step by step"; set effort / budget instead.
    3. Thinking tokens are billed as OUTPUT (the expensive kind) and add
       latency before the first visible token. Budget for both.
    4. temperature / top_p are often fixed or rejected (lesson 02 PART 9).
    5. Don't parse or show raw thinking to users; use the answer block.
""")


# ============================================================================
# PART 4: Three levels of structured output -- measured
# ============================================================================
# WHAT EACH LEVEL GUARANTEES
#   level             parses?   matches schema?   correct values?
#   ┌───────────────┬─────────┬─────────────────┬─────────────────┐
#   │ prompt only   │ ✗ maybe │ ✗ maybe         │ ✗ validate      │
#   │ JSON mode     │ ✓       │ ✗ maybe         │ ✗ validate      │
#   │ schema decode │ ✓       │ ✓               │ ✗ validate      │
#   └───────────────┴─────────┴─────────────────┴─────────────────┘
#   all three: max_tokens can still cut the output ─▶ check stop_reason

CATEGORIES = {"bug", "feature", "question"}
GOOD = {"category": "bug", "priority": 2, "summary": "Login button does nothing"}


def render(defect: str) -> str:
    """Turn a defect name into the concrete text a model might emit."""
    ok = json.dumps(GOOD)
    variants = {
        "ok": ok,
        "prose": "Sure! Here is the JSON:\n" + ok,
        "fence": "```json\n" + ok + "\n```",
        "trailing_comma": ok[:-1] + ", }",
        "single_quotes": str(GOOD),
        "truncated": ok[: len(ok) // 2],
        "missing_field": json.dumps({k: v for k, v in GOOD.items() if k != "priority"}),
        "bad_enum": json.dumps({**GOOD, "category": "crash"}),
        "wrong_type": json.dumps({**GOOD, "priority": "high"}),
        "extra_key": json.dumps({**GOOD, "confidence": 0.9}),
    }
    return variants[defect]


def check(text: str) -> tuple[str, str]:
    """Return (outcome, reason). outcome: 'not JSON' | 'wrong shape' | 'valid'."""
    try:
        data = json.loads(text)
    except json.JSONDecodeError as e:
        return "not JSON", e.msg
    if not isinstance(data, dict) or set(data) != {"category", "priority", "summary"}:
        return "wrong shape", "keys differ from schema"
    if data["category"] not in CATEGORIES:
        return "wrong shape", "category not in enum"
    if not isinstance(data["priority"], int) or not 1 <= data["priority"] <= 5:
        return "wrong shape", "priority not int 1-5"
    return "valid", ""


# Simulated defect mix per level (weights out of 100). JSON mode removes
# syntax errors; schema decoding removes shape errors; truncation by
# max_tokens survives every level.
LEVELS = {
    "prompt only": {"ok": 78, "prose": 5, "fence": 5, "trailing_comma": 2,
                    "single_quotes": 2, "truncated": 1, "missing_field": 2,
                    "bad_enum": 3, "wrong_type": 1, "extra_key": 1},
    "JSON mode": {"ok": 89, "truncated": 1, "missing_field": 3, "bad_enum": 4,
                  "wrong_type": 2, "extra_key": 1},
    "schema-constrained": {"ok": 99, "truncated": 1},
}


def part4_three_levels():
    print("######## PART 4 -- Three levels of structured output (SIMULATED) ########\n")
    print(f"  Schema: {{category: bug|feature|question, priority: int 1-5, summary: str}}")
    print("  200 simulated outputs per level, each checked by REAL json.loads + schema check\n")
    print(f"  {'level':<20} {'not JSON':>9} {'wrong shape':>12} {'valid':>7}   failure rate")
    for i, (level, weights) in enumerate(LEVELS.items()):
        rng = random.Random(40 + i)
        defects = rng.choices(list(weights), weights=list(weights.values()), k=200)
        tally = {"not JSON": 0, "wrong shape": 0, "valid": 0}
        reasons = {}
        for d in defects:
            outcome, reason = check(render(d))
            tally[outcome] += 1
            if reason:
                reasons[reason] = reasons.get(reason, 0) + 1
        fail = 1 - tally["valid"] / 200
        print(f"  {level:<20} {tally['not JSON']:>9} {tally['wrong shape']:>12} "
              f"{tally['valid']:>7}   {bar(fail * 5, 10)} {fail:5.1%}")
        top = sorted(reasons.items(), key=lambda kv: -kv[1])[:2]
        print(f"  {'':<4} top reasons: {', '.join(f'{r} x{n}' for r, n in top) or '-'}")
    print("""
  (failure bar is scaled x5 so small rates stay visible)
  - prompt only: prose wrappers, ``` fences and Python-style quotes break
    json.loads. You end up writing fragile "find the braces" code.
  - JSON mode: parses (unless cut off), but the SHAPE is the model's guess.
  - schema-constrained: shape guaranteed; the remaining failures are
    max_tokens truncation at EVERY level -> check stop_reason (lesson 03
    PART 6) before parsing.
  None of them guarantee the VALUES are right. Still validate (PART 6).
""")


# ============================================================================
# PART 5: Constrained decoding, mechanically
# ============================================================================
# EACH STEP: LOGITS ─▶ MASK ─▶ PICK   (grammar: {"label":"a"|"b","score":D})
#   model logits  Sure ██████  {  █████  "c" ███  10 ██  ...
#                   │
#   grammar mask  ──┼──▶ allowed now? {  ✓   Sure ✗  "c" ✗  10 ✗
#                   ▼
#   masked logits  ✗ = -inf ─▶ softmax ─▶ only valid tokens left ─▶ pick
#   state 0 { ─▶ 1 "label" ─▶ 2 : ─▶ 3 "a"|"b" ─▶ 4 , ─▶ 5 "score"
#           ─▶ 6 : ─▶ 7 digit ─▶ 8 } ─▶ done   (always parses + matches)

DIGITS = [str(d) for d in range(10)]
VOCAB = ["{", "}", ":", ",", '"label"', '"score"', '"a"', '"b"', '"c"',
         "Sure", "Here", "\n", "10", "null"] + DIGITS
GRAMMAR = [{"{"}, {'"label"'}, {":"}, {'"a"', '"b"'}, {","}, {'"score"'},
           {":"}, set(DIGITS), {"}"}]
# What this toy model "wants" at each step (it is chatty and makes
# out-of-schema choices at steps 0, 3 and 7).
FAVOURITE = {0: "Sure", 3: '"c"', 7: "10"}
RUNNER_UP = {0: "{", 1: '"label"', 2: ":", 3: '"a"', 4: ",", 5: '"score"',
             6: ":", 7: "7", 8: "}"}


def toy_logits(step: int) -> dict[str, float]:
    rng = random.Random(500 + step)
    logits = {tok: rng.uniform(-3, 0) for tok in VOCAB}
    logits[RUNNER_UP[step]] = 3.0
    if step in FAVOURITE:
        logits[FAVOURITE[step]] = 4.0
    return logits


def decode(constrained: bool) -> tuple[str, list]:
    out, trace = [], []
    for step, allowed in enumerate(GRAMMAR):
        logits = toy_logits(step)
        favourite = max(logits, key=lambda t: logits[t])
        if constrained:
            logits = {t: (v if t in allowed else -math.inf) for t, v in logits.items()}
        pick = max(logits, key=lambda t: logits[t])
        trace.append((step, allowed, favourite, pick))
        out.append(pick)
    return "".join(out), trace


def part5_constrained_decoding():
    print("######## PART 5 -- Constrained decoding, step by step ########\n")
    print(f"  Toy vocabulary ({len(VOCAB)} tokens): {' '.join(repr(t)[1:-1] for t in VOCAB)}")
    print('  Toy grammar: {"label": "a"|"b", "score": <one digit>}  (greedy picks)\n')
    _, trace = decode(constrained=True)
    print(f"  {'step':>4}  {'allowed now':<20} {'n':>3}/{len(VOCAB)}  "
          f"{'model wants':<12} picked")
    for step, allowed, fav, pick in trace:
        shown = "0-9" if allowed == set(DIGITS) else " ".join(sorted(allowed))
        flag = "  <- masked its favourite" if fav != pick else ""
        print(f"  {step:>4}  {shown:<20} {len(allowed):>3}/{len(VOCAB)}  "
              f"{fav:<12} {pick}{flag}")
    for constrained in (False, True):
        text, _ = decode(constrained)
        try:
            json.loads(text)
            verdict = "parses OK"
        except json.JSONDecodeError as e:
            verdict = f"json.loads fails: {e.msg}"
        label = "constrained  " if constrained else "unconstrained"
        print(f"\n  {label}: {text!r}\n      -> {verdict}")
    print("""
  The model's probabilities are unchanged; the decoder just sets every
  token that would break the grammar to -inf before sampling. Real
  engines compile your JSON Schema into such a grammar / state machine
  (with branches for key order, optional fields, nested objects, string
  characters). Cost: a little compile time per new schema, and very
  large or deeply nested schemas may be rejected or slow.
""")


