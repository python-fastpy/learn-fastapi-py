# WHAT THE MODEL CAN READ  (text height after the image is downscaled)
#   4K screenshot, 12px UI ─▶ fit 1568px (÷2.45) ─▶  4.9px ░ model GUESSES
#   800x400 crop, 12px UI  ─▶ no downscale (÷1)  ─▶ 12.0px █ readable
#   rule of thumb (toy): < 8px text height ─▶ high hallucination risk
#   ┌────────┐  resize  ┌──────┐  crop  ┌───┐  OCR'd text? ─▶ send TEXT
#   │ 4032px │ ───────▶ │1568px│ ─────▶ │ROI│  else         ─▶ send image
#   └────────┘          └──────┘        └───┘

MIN_READABLE_PX = 8    # toy threshold


def text_height_after(w, h, text_px):
    fw, _ = fit(w, h, 1568)
    return text_px * fw / w


def part8_rules():
    print("######## PART 8 -- Practical multimodal rules ########\n")
    raw = tokens_area(4032, 3024)
    print(f"  Resize: a phone photo is fitted to 1568px anyway -> {raw:,} tokens either")
    print(f"  way, but uploading 4032x3024 wastes bandwidth and latency. Resize first.\n")
    full, crop = tokens_area(1920, 1080), tokens_area(600, 300)
    print(f"  Crop: full screenshot {full:,} tokens vs 600x300 error dialog {crop:,} "
          f"tokens ({1 - crop / full:.0%} saved)\n")
    print("  Small text: height of the text the model actually sees (formula B fit):")
    cases = [("receipt photo 4032x3024, 30px text", 4032, 3024, 30),
             ("full page 1700x2200, 14px footnote", 1700, 2200, 14),
             ("4K screenshot 3840x2160, 12px UI", 3840, 2160, 12),
             ("crop 800x400 of that UI, 12px", 800, 400, 12)]
    for name, w, h, px in cases:
        seen = text_height_after(w, h, px)
        risk = "HIGH risk: model may guess" if seen < MIN_READABLE_PX else "readable"
        print(f"    {name:<38} -> {seen:5.1f}px  {bar(seen / 16, 10)}  {risk}")
    ocr_text = "Invoice INV-0042 total EUR 1,250.00 due 2026-03-31"
    print(f"\n  OCR: if the text is extractable, send it as text: "
          f"{est_tokens(ocr_text)} tokens vs an image crop ~{crop:,} tokens")
    print("""
  Checklist before sending an image:
    [ ] resized to the model's max useful size (no bigger)
    [ ] cropped to the region that answers the question
    [ ] text that can be extracted (PDF text layer, OCR) sent as TEXT
    [ ] small text at least ~8px tall after resizing, or crop/zoom it
    [ ] ask for "unreadable" as an allowed answer, not a guess
    [ ] numbers read from images checked in code (PART 6) or by a human
""")


